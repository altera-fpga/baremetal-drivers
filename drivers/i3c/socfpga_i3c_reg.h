#define I3C_INTR_STATUS_TRANSFER_ABORT_POS 5U
#define I3C_INTR_STATUS_TRANSFER_ERR_MASK 0x00000200U
#define I3C_INTR_STATUS_TRANSFER_ERR_POS 9U
#define I3C_INTR_STATUS_ALL_MASK         0x00003F7FU

#define I3C_QUEUE_STATUS_LEVEL_CMD_MASK  0x000000FFU
#define I3C_QUEUE_STATUS_LEVEL_CMD_POS   0U
#define I3C_QUEUE_STATUS_LEVEL_RESP_MASK 0x0000FF00U
#define I3C_QUEUE_STATUS_LEVEL_RESP_POS  8U

#define I3C_DATA_BUFFER_STATUS_LEVEL_TX_MASK 0x000000FFU
#define I3C_DATA_BUFFER_STATUS_LEVEL_TX_POS  0U

#define I3C_DEVICE_ADDR_TABLE_POINTER_ADDR_MASK  0x000000FFU
#define I3C_DEVICE_ADDR_TABLE_POINTER_DEPTH_MASK 0xFFFF0000U
#define I3C_DEVICE_ADDR_TABLE_POINTER_DEPTH_POS  16U

#define I3C_RESP_DATA_LENGTH_MASK        0x0000FFFFU
#define I3C_RESP_DATA_LENGTH_POS         0U
