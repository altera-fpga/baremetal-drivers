#define I3C_RESP_DATA_ID_POS             24U
#define I3C_RESP_ERR_STATUS_MASK         0xF0000000U
#define I3C_RESP_ERR_STATUS_POS          28U

#define I3C_CMD_XFER_ATTR_MASK           0x00000007U
#define I3C_CMD_XFER_ATTR_POS            0U
#define I3C_CMD_TRANSACTION_ID_MASK      0x00000078U
#define I3C_CMD_TRANSACTION_ID_POS       3U
#define I3C_CMD_COMMAND_CODE_MASK        0x00007F80U
#define I3C_CMD_COMMAND_CODE_POS         7U
#define I3C_CMD_COMMAND_PRESENT_MASK     0x00008000U
#define I3C_CMD_COMMAND_PRESENT_POS      15U
