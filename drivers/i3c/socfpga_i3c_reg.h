#define I3C_RESET_CTRL_RX_FIFO_MASK      0x00000010U
#define I3C_RESET_CTRL_IBI_QUEUE_MASK    0x00000020U
#define I3C_RESET_CTRL_XFER_QUEUES_MASK  (I3C_RESET_CTRL_CMD_QUEUE_MASK | \
                                           I3C_RESET_CTRL_RESP_QUEUE_MASK | \
                                           I3C_RESET_CTRL_TX_FIFO_MASK | \
                                           I3C_RESET_CTRL_RX_FIFO_MASK)

#endif /* SOCFPGA_I3C_REG_H */
