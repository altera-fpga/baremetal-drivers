#define I3C_INTR_STATUS_IBI_THLD_POS     2U
#define I3C_INTR_STATUS_CMD_READY_MASK   0x00000008U
#define I3C_INTR_STATUS_CMD_READY_POS    3U
#define I3C_INTR_STATUS_RESP_READY_MASK  0x00000010U
#define I3C_INTR_STATUS_RESP_READY_POS   4U
