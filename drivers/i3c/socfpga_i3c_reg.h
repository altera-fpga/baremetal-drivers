#define I3C_DAT_LEGACY_I2C_DEV_MASK      0x80000000U
#define I3C_DAT_DYNAMIC_ADDR(x)          (((uint32_t)(x) << 16) & 0x00FF0000U)
#define I3C_DAT_STATIC_ADDR(x)           ((uint32_t)(x) & 0x0000007FU)

#define I3C_DEVICE_CTRL_IBA_INCLUDE_MASK 0x00000001U
