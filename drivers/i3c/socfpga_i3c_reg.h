#define I3C_RX_TX_DATA_PORT              I3C_TX_DATA_PORT

#define I3C_COMMAND_PORT_TID(x)          (((uint32_t)(x) << 3) & 0x00000078U)
#define I3C_COMMAND_PORT_DEV_INDEX(x)    (((uint32_t)(x) << 16) & 0x001F0000U)
#define I3C_COMMAND_PORT_SPEED(x)        (((uint32_t)(x) << 21) & 0x00E00000U)
