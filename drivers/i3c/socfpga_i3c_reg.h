#define I3C_CMD_RESP_ON_COMPLETION_POS   30U

#define I3C_RESET_CTRL_SOFT_RST_MASK     0x00000001U
#define I3C_RESET_CTRL_SOFT_RST_POS      0U
#define I3C_RESET_CTRL_CMD_QUEUE_MASK    0x00000002U
#define I3C_RESET_CTRL_RESP_QUEUE_MASK   0x00000004U
